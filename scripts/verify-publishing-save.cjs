// Requires only the main repository dev server at :3000; blocks all real API calls.
const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const path = require("node:path");
const fsUrl = name => "/@fs/" + path.resolve(__dirname, "fixtures", name);
(async () => {
  const browser = await chromium.launch({ headless: true, channel: "chrome" });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.route("**/api/**", route => { errors.push("Real API blocked: " + route.request().url()); return route.abort(); });
    await page.route("**/StoryAgentContext.tsx*", route => route.fulfill({ contentType: "application/javascript", body: `export * from ${JSON.stringify(fsUrl("publishing-save-context.ts"))};` }));
    await page.route("**/__qa-publishing-save", route => route.fulfill({ contentType: "text/html", body: `<!doctype html><html><head><script type="module">import RefreshRuntime from '/@react-refresh';RefreshRuntime.injectIntoGlobalHook(window);window.$RefreshReg$=()=>{};window.$RefreshSig$=()=>type=>type;window.__vite_plugin_react_preamble_installed__=true;</script></head><body><div id="root"></div><script type="module" src="${fsUrl("publishing-save.tsx")}"></script></body></html>` }));
    await page.goto("http://localhost:3000/__qa-publishing-save");
    const body = page.locator("#publishing-body");
    const save = page.getByRole("button", { name: "保存", exact: true });
    await body.waitFor();
    const text = "爷爷修好了那把旧伞。雨停的时候，我们一起走出了家门。";
    await body.fill(text);
    await page.getByRole("button", { name: "配图", exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: "/tmp/publishing-article-image-button.png", fullPage: true });
    await save.click();
    await page.getByRole("status").filter({ hasText: "已保存" }).waitFor();
    assert.equal(await page.getByRole("dialog").count(), 0);
    assert.equal(await page.evaluate(() => __qa.saved().drafts.xiaohongshu.content.body), text);
    assert.equal(await page.evaluate(() => __qa.saved().core.facts[0]), "虚构故事");
    assert.deepEqual(await page.evaluate(() => __qa.calls.filter(c => c.type === "mutation").map(c => c.path)), ["publishingDraft.applyEdit"]);
    await page.screenshot({ path: "/tmp/publishing-direct-save.png", fullPage: true });
    // Text typed after a save starts must remain editable and dirty.
    await body.fill("保存中的第一稿");
    await page.evaluate(() => { __qa.hold = true; });
    await save.click();
    await page.getByRole("button", { name: "正在保存…", exact: true }).waitFor();
    await body.fill("保存过程中继续补充的文字");
    await page.evaluate(() => __qa.release());
    await save.waitFor();
    assert.equal(await body.inputValue(), "保存过程中继续补充的文字");
    assert.equal(await page.evaluate(() => __qa.saved().drafts.xiaohongshu.content.body), "保存中的第一稿");
    // A rejected save preserves the text and offers retry without a decision modal.
    await page.evaluate(() => { __qa.hold = false; __qa.fail = true; });
    await save.click();
    await page.getByText("这份发布稿已经在别处更新，请刷新后再应用", { exact: true }).waitFor();
    assert.equal(await body.inputValue(), "保存过程中继续补充的文字");
    assert.equal(await page.getByRole("dialog").count(), 0);
    await page.evaluate(() => { __qa.fail = false; });
    await save.click();
    await page.getByRole("status").filter({ hasText: "已保存" }).waitFor();
    assert.equal(await page.evaluate(() => __qa.saved().drafts.xiaohongshu.content.body), "保存过程中继续补充的文字");
    // Reverting to the old saved text during an in-flight save is still a new edit.
    await page.evaluate(() => { __qa.hold = true; });
    await body.fill("等待保存的临时改稿");
    await save.click();
    await page.getByRole("button", { name: "正在保存…", exact: true }).waitFor();
    await body.fill("保存过程中继续补充的文字");
    await page.evaluate(() => __qa.release());
    await save.waitFor();
    assert.equal(await body.inputValue(), "保存过程中继续补充的文字");
    assert.equal(await page.evaluate(() => __qa.saved().drafts.xiaohongshu.content.body), "等待保存的临时改稿");
    // Reproduce the blocked image modal, then save from inside it.
    await page.evaluate(() => { __qa.hold = false; __qa.fail = true; });
    const beforeNavigation = await page.evaluate(() => __qa.calls.filter(c => c.type === "mutation").length);
    await page.getByRole("button", { name: "配图", exact: true }).scrollIntoViewIfNeeded();
    await page.getByRole("button", { name: "配图", exact: true }).click();
    await page.getByRole("region", { name: "图像工作区" }).waitFor();
    assert.equal(await page.evaluate(() => __qa.calls.filter(c => c.type === "mutation").length), beforeNavigation);
    await page.getByRole("button", { name: "切换测试工作区" }).click();
    assert.equal(await body.inputValue(), "保存过程中继续补充的文字");
    await page.getByRole("button", { name: "配图", exact: true }).click();
    await page.getByRole("button", { name: "生成图片", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "基于当前文案生成图片" });
    const saveForImages = dialog.getByRole("button", { name: "保存文案，继续", exact: true });
    await saveForImages.waitFor();
    assert.equal(await saveForImages.isEnabled(), true);
    await dialog.getByRole("textbox", { name: "图片生成要求" }).fill("雨后窗边的旧伞，水彩风格");
    const countGenerations = () => page.evaluate(() => __qa.calls.filter(c => c.path === "publishingDraft.generateCover").length);
    assert.equal(await countGenerations(), 0);
    await saveForImages.click();
    await page.getByText("这份发布稿已经在别处更新，请刷新后再应用", { exact: true }).waitFor();
    assert.equal(await saveForImages.isVisible(), true);
    assert.equal(await countGenerations(), 0);
    assert.equal(await dialog.getByRole("textbox", { name: "图片生成要求" }).inputValue(), "雨后窗边的旧伞，水彩风格");
    await page.evaluate(() => { __qa.fail = false; __qa.hold = true; });
    await saveForImages.click();
    const savingForImages = dialog.getByRole("button", { name: "正在保存文案…", exact: true });
    await savingForImages.waitFor();
    assert.equal(await savingForImages.isEnabled(), false);
    await page.evaluate(() => __qa.release());
    const confirm = dialog.getByRole("button", { name: /确认生成 4 张/ });
    await confirm.waitFor();
    assert.equal(await confirm.isEnabled(), true);
    assert.equal(await countGenerations(), 0);
    assert.equal(await dialog.getByRole("textbox", { name: "图片生成要求" }).inputValue(), "雨后窗边的旧伞，水彩风格");
    await page.screenshot({ path: "/tmp/publishing-image-save-ready.png", fullPage: true });
    await confirm.click();
    await page.waitForFunction(() => __qa.calls.some(c => c.path === "publishingDraft.generateCover"));
    const generation = await page.evaluate(() => __qa.calls.find(c => c.path === "publishingDraft.generateCover").input);
    assert.equal(generation.basePublishingRevision, await page.evaluate(() => __qa.saved().revision));
    assert.equal(generation.feedback, "雨后窗边的旧伞，水彩风格");
    assert.equal(generation.costConfirmation.accepted, true);
    assert.equal(await countGenerations(), 1);
    assert.deepEqual(errors, []);
    console.log("PASS: direct save, no modal, no core mutation, in-flight edits, conflict and retry; image-dialog save/retry/explicit generation with latest revision; no real API requests.");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
